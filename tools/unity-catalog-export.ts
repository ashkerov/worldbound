// Генератор C#-каталогов флоры для Unity (Stage 2.0): content/plants/plants.json и content/biomes/biomes.json →
// PlantCatalog.g.cs и BiomeCatalog.g.cs. Источник истины — JSON; записи берутся уже прочитанными и проверенными
// настоящими загрузчиками TS (loadPlants, loadBiomes — со схемами), числа выгружаются точными битами IEEE-754
// (в Unity Mono разбор десятичного текста не всегда даёт тот же double). В файл записывается SHA-256 исходного JSON
// (байты файла с окончаниями строк LF), C# сверяет его с файлом на диске (golden G0).
// Использование: npx tsx tools/unity-catalog-export.ts          — записать файлы
//                npx tsx tools/unity-catalog-export.ts --check  — проверить, что файлы соответствуют JSON (код 1, если нет)

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { PLANTS, type PlantSpecies } from '../src/sim/flora/species';
import { BIOMES, type BiomeRule } from '../src/sim/flora/biomes';
import { SOILS } from '../src/sim/env/soils';

const OUT_DIR = 'unity/WorldboundProto/Assets/Worldbound/Sim/Flora/Catalog';
const PLANTS_JSON = 'content/plants/plants.json';
const BIOMES_JSON = 'content/biomes/biomes.json';
const check = process.argv.includes('--check');

/** SHA-256 файла с окончаниями строк LF (не зависит от настроек checkout). */
export function catalogSha256(path: string): string {
  const text = readFileSync(path).toString('latin1').replace(/\r\n/g, '\n');
  return createHash('sha256').update(Buffer.from(text, 'latin1')).digest('hex');
}

export function bits(x: number): string {
  const b = Buffer.alloc(8);
  b.writeDoubleBE(x);
  return '0x' + b.toString('hex').toUpperCase() + 'UL';
}

const d = (x: number) => `B(${bits(x)}) /* ${x} */`;
const dn = (x: number | undefined) => (x === undefined ? 'null' : d(x));
const q = (s: string) => JSON.stringify(s);
const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

function plantEntry(p: PlantSpecies): string {
  const soils = SOILS.filter((s) => p.soilPreference?.[s.id] !== undefined).map((s) => `(${q(s.id)}, ${d(p.soilPreference![s.id]!)})`);
  const lines = [
    `Id = ${q(p.id)}`,
    `Name = ${q(p.name)}`,
    `Form = PlantForm.${pascal(p.form)}`,
    `LeafHabit = LeafHabit.${pascal(p.leafHabit)}`,
    `Community = ${p.community ? `HerbCommunity.${pascal(p.community)}` : 'null'}`,
    `Temperature = new Range4(${d(p.temperature.min)}, ${d(p.temperature.optMin)}, ${d(p.temperature.optMax)}, ${d(p.temperature.max)})`,
    `FrostKill = ${d(p.frostKill)}`,
    `Moisture = new Range4(${d(p.moisture.min)}, ${d(p.moisture.optMin)}, ${d(p.moisture.optMax)}, ${d(p.moisture.max)})`,
    `ShadeTolerance = ${d(p.shadeTolerance)}`,
    `NutrientDemand = ${d(p.nutrientDemand)}`,
    `GrowthRate = ${d(p.growthRate)}`,
    `MaxBiomass = ${d(p.maxBiomass)}`,
    `HalfBiomass = ${dn(p.halfBiomass)}`,
    `MaxHeight = ${dn(p.maxHeight)}`,
    `MaxCrownRadius = ${dn(p.maxCrownRadius)}`,
    `NutrientContent = ${d(p.nutrientContent)}`,
    `LeafFraction = ${dn(p.leafFraction)}`,
    `CanopyTransmission = ${dn(p.canopyTransmission)}`,
    `MaturityYears = ${dn(p.maturityYears)}`,
    `LifespanYears = ${dn(p.lifespanYears)}`,
    `BaseMortality = ${d(p.baseMortality)}`,
    `SeedMass = ${d(p.seedMass)}`,
    `Fecundity = ${dn(p.fecundity)}`,
    `DispersalMean = ${dn(p.dispersal?.mean)}`,
    `DispersalMax = ${dn(p.dispersal?.max)}`,
    `Establishment = ${d(p.establishment)}`,
    `SeedAllocation = ${dn(p.seedAllocation)}`,
    `SeedBankYears = ${dn(p.seedBankYears)}`,
    `FixesNutrient = ${dn(p.fixesNutrient)}`,
    `LitterQuality = ${d(p.litterQuality)}`,
    `ColonistWeight = ${d(p.colonistWeight)}`,
    `SoilPreference = ${p.soilPreference ? `new (string, double)[] { ${soils.join(', ')} }` : 'null'}`,
  ];
  return `            new PlantSpecies\n            {\n${lines.map((l) => `                ${l},`).join('\n')}\n            },`;
}

const RULE_FIELDS: (keyof BiomeRule)[] = [
  'treeCoverMin', 'treeCoverMax', 'shrubCoverMin', 'tallShareMin', 'tallShareMax', 'herbBiomassMin', 'herbBiomassMax',
  'coniferShareMin', 'coniferShareMax', 'tMeanMin', 'tMeanMax', 'moistureMin', 'moistureMax', 'steppeShareMin', 'steppeShareMax',
  'wetShareMin', 'pioneerShareMin',
];

const header = (src: string, sha: string) => `// <auto-generated>
// Сгенерировано tools/unity-catalog-export.ts из ${src} — не править вручную.
// Источник истины — JSON; числа — точные биты IEEE-754 значений, прочитанных загрузчиком TS (со схемой).
// SHA-256 источника (LF): ${sha}
// </auto-generated>
`;

function plantsFile(): string {
  const raw = JSON.parse(readFileSync(PLANTS_JSON, 'utf8')) as { version: number; calibration?: { status?: string; fields?: Record<string, string> } };
  const sha = catalogSha256(PLANTS_JSON);
  const cal = raw.calibration ?? {};
  const fields = Object.entries(cal.fields ?? {}).map(([k, v]) => `            (${q(k)}, ${q(v)}),`);
  return `${header(PLANTS_JSON, sha)}using System;

namespace Worldbound.Sim.Flora
{
    public static partial class PlantCatalog
    {
        public const string SourceFile = ${q(PLANTS_JSON)};
        public const string SourceSha256 = ${q(sha)};
        public const int Version = ${raw.version};
        /** Статус калибровки (пояснение из блока calibration; на расчёты не влияет — числа калибровки — поля видов). */
        public const string CalibrationStatus = ${q(cal.status ?? '')};
        public static readonly (string Field, string Note)[] CalibrationNotes =
        {
${fields.join('\n')}
        };

        static double B(ulong bits) => BitConverter.Int64BitsToDouble(unchecked((long)bits));

        /// <summary>Виды в порядке каталога (индекс записи — номер вида в симуляции).</summary>
        public static readonly PlantSpecies[] All =
        {
${PLANTS.map(plantEntry).join('\n')}
        };
    }
}
`;
}

function biomesFile(): string {
  const raw = JSON.parse(readFileSync(BIOMES_JSON, 'utf8')) as { version: number };
  const sha = catalogSha256(BIOMES_JSON);
  const entries = BIOMES.map((b) => {
    const r = b.rule;
    const water = r.water ? `new byte[] { ${r.water.map((w) => ({ river: 1, lake: 2, sea: 3 })[w]).join(', ')} }` : 'null';
    const fields = RULE_FIELDS.map((f) => `${pascal(f)} = ${dn(r[f] as number | undefined)}`);
    return `            new Biome\n            {\n                Id = ${q(b.id)},\n                Name = ${q(b.name)},\n                Color = ${q(b.color)},\n                Rule = new BiomeRule\n                {\n                    Water = ${water},\n${fields.map((l) => `                    ${l},`).join('\n')}\n                },\n            },`;
  });
  return `${header(BIOMES_JSON, sha)}using System;

namespace Worldbound.Sim.Flora
{
    public static partial class BiomeCatalog
    {
        public const string SourceFile = ${q(BIOMES_JSON)};
        public const string SourceSha256 = ${q(sha)};
        public const int Version = ${raw.version};

        static double B(ulong bits) => BitConverter.Int64BitsToDouble(unchecked((long)bits));

        /// <summary>Биомы в порядке каталога: первое совпавшее правило; последний — без условий (по умолчанию).</summary>
        public static readonly Biome[] All =
        {
${entries.join('\n')}
        };
    }
}
`;
}

const files: [string, string][] = [
  [`${OUT_DIR}/PlantCatalog.g.cs`, plantsFile()],
  [`${OUT_DIR}/BiomeCatalog.g.cs`, biomesFile()],
];
let stale = 0;
for (const [path, text] of files) {
  if (check) {
    const cur = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== text) {
      console.error(`${path}: не соответствует ${path.includes('Plant') ? PLANTS_JSON : BIOMES_JSON} — перегенерируйте: npx tsx tools/unity-catalog-export.ts`);
      stale++;
    } else console.log(`${path}: соответствует источнику`);
  } else {
    writeFileSync(path, text);
    console.log(`→ ${path}`);
  }
}
if (check && stale > 0) process.exit(1);
